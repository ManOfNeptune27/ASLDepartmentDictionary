<main class="container py-5 content-page">
  <h1>About the ASL Department Dictionary</h1>
  <p>
    The ASL Department Dictionary is a teaching and reference project for organizing
    American Sign Language vocabulary in one searchable place.
  </p>
  <p>
    Signs are contributed by ASL teachers and organized by source, including Signing
    Naturally, True Way ASL, and Miscellaneous, and then by category. Use the search box
    or choose a source and category on the dictionary home page to find a sign.
  </p>

  <h2>Who the dictionary is for</h2>
  <p>
    The dictionary is designed primarily for ASL students who want to review vocabulary
    outside the classroom. Students can use it to practice words from their current unit,
    compare sign parameters, and revisit signs while studying for class or completing
    assignments.
  </p>
  <p>
    ASL teachers and tutors can also use the dictionary as a review aid when preparing
    lessons or helping students practice. Families, friends, and community members may
    use it as an introduction to vocabulary they encounter while learning about American
    Sign Language. The dictionary is a reference tool for practice and review; it does
    not replace instruction from a qualified ASL teacher or interaction with Deaf
    community members.
  </p>

  <h2>Who maintains it</h2>
  <p>
    The dictionary is maintained by ASL teachers and contributors who review and add
    entries for students and fellow educators.
  </p>

  <h2>How signs are added</h2>
  <p>
    Teachers add each sign directly to the dictionary. The word, gloss, sign parameters,
    source, category, and other details are entered by the teachers themselves based on
    their knowledge and classroom experience. This helps keep the information connected
    to the way ASL is taught and used by educators.
  </p>

  <h2>How the vocabulary is organized</h2>
  <p>
    SN means Signing Naturally and TWA means True Way ASL. These labels describe the
    textbook organization used for vocabulary. The site does not reproduce content from
    those books.
  </p>

  <h2>Contributed media</h2>
  <p>
    Signs and GIFs are contributed by ASL teachers who gave permission for their use.
  </p>

