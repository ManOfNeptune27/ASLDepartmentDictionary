  <h1>Fingerspelling Basics</h1>
  <p>
    Fingerspelling represents words with a sequence of handshapes. It can help identify
    names, places, technical terms, and words that do not yet have a shared sign in a
    particular conversation.
  </p>

  <h2>Start with clear handshapes</h2>
  <p>
    Practice each handshape separately before working on speed. Keep the hand visible,
    use a comfortable position, and pay attention to the differences between neighboring
    letters. Clarity is more useful than rushing.
  </p>

  <h2>Use movement with purpose</h2>
  <p>
    Fingerspelling is produced as a connected sequence rather than as unrelated poses.
    The rhythm, transitions, and movement of the hand can affect how easily the word is
    understood. Watch experienced signers and follow the conventions taught in your class.
  </p>

  <h2>Read the whole conversation</h2>
  <p>
    Fingerspelling works with the surrounding ASL message. Use context, repetition, and
    clarification when a word is unfamiliar. Different communities and settings may
    have different preferences for speed, space, and style.
  </p>

