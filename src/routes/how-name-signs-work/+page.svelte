  <h1>How Name Signs Work</h1>
  <p>
    A name sign is a sign used to identify a person within an ASL community. Name signs
    are connected to relationships, community history, and how people are known by the
    people around them.
  </p>

  <h2>Community and consent</h2>
  <p>
    Name signs are not generally chosen casually by an outsider. A person's community
    may establish or use a name sign, and the person should be comfortable with how it
    is used. Context matters: the same handshape or movement can have different meanings
    in different communities.
  </p>

  <h2>Descriptive and arbitrary patterns</h2>
  <p>
    Some name signs relate to a person's appearance, personality, interests, or a
    memorable event. Other name signs are more arbitrary and become meaningful through
    repeated community use. The important information is not just the dictionary gloss,
    but the person and community connected to the sign.
  </p>

  <h2>Learning respectfully</h2>
  <p>
    Learners should ask qualified Deaf or ASL educators about local conventions rather
    than assigning name signs to themselves or to other people. Observe how a sign is
    used, ask about its meaning when appropriate, and respect a person's preference.
  </p>
